export function realtimePolicyFor(type: string): RealtimePolicy | null {
  const selected = eventPolicies[type];
  return selected ? { topics: [...selected.topics], staff: selected.staff } : null;
}

function policy(...topics: RealtimeTopic[]): RealtimePolicy {
  return { topics, staff: true };
}
