export function formatOtpDigitLabel(copy: LoginCopy, index: number, total: number): string {
  return copy.otpDigitLabel
    .replace('{current}', String(index + 1))
    .replace('{total}', String(total));
}

export function getLoginCopy(locale: Locale): LoginCopy {
  return locale === 'ar' ? ar : en;
}
